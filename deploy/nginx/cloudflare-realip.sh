#!/bin/sh
# Writes /etc/nginx/conf.d/cloudflare-realip.conf:
#   * nginx takes the visitor IP from CF-Connecting-IP, but only when the request comes from a Cloudflare edge;
#   * $from_cloudflare = 1 for Cloudflare edges, so a site can refuse anything that bypasses Cloudflare
#     (the agora site does: `if ($from_cloudflare = 0) { return 444; }`).
# Re-run occasionally: Cloudflare publishes its ranges at https://www.cloudflare.com/ips/
set -eu
RANGES=$(for u in https://www.cloudflare.com/ips-v4 https://www.cloudflare.com/ips-v6; do curl -fsS --max-time 20 "$u"; echo; done | grep -E '^[0-9a-f:.]+/[0-9]+$')
[ -n "$RANGES" ] || { echo "could not fetch Cloudflare ranges" >&2; exit 1; }
{ echo "# generated by deploy/nginx/cloudflare-realip.sh"
  echo "$RANGES" | sed 's/^/set_real_ip_from /; s/$/;/'
  echo "real_ip_header CF-Connecting-IP;"
  echo 'geo $realip_remote_addr $from_cloudflare {'
  echo "    default 0;"
  echo "$RANGES" | sed 's/^/    /; s/$/ 1;/'
  echo "}"; } | sudo tee /etc/nginx/conf.d/cloudflare-realip.conf > /dev/null
sudo nginx -t && sudo systemctl reload nginx
